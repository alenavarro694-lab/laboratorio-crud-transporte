    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
      if (!validarCampos()) return;

        Camion c = new Camion();
        c.setModelo(txtModelo.getText().trim());
        c.setTipo(txtTipo.getText().trim());
        c.setPotencia(new BigDecimal(txtPotencia.getText().trim()));
        c.setNoPlaca(txtPlaca.getText().trim());

        if (camionDAO.insertar(c)) {
            JOptionPane.showMessageDialog(this, "Camión guardado exitosamente.");
            cargarCamiones();
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar el camión.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un camión de la tabla para actualizar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!validarCampos()) return;

        try {
            Camion c = new Camion();
            c.setIdCamion(Integer.parseInt(txtId.getText().trim()));
            c.setModelo(txtModelo.getText().trim());
            c.setTipo(txtTipo.getText().trim());
            c.setPotencia(new BigDecimal(txtPotencia.getText().trim()));
            c.setNoPlaca(txtPlaca.getText().trim());

            if (camionDAO.actualizar(c)) {
                JOptionPane.showMessageDialog(this, "Camión actualizado exitosamente.");
                cargarCamiones();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "Error al actualizar el camión.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un camión de la tabla para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int op = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el camión seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (op == JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(txtId.getText().trim());
                if (camionDAO.eliminar(id)) {
                    JOptionPane.showMessageDialog(this, "Camión eliminado exitosamente.");
                    cargarCamiones();
                    limpiarCampos();
                } else {
                    JOptionPane.showMessageDialog(this, "Error al eliminar el camión.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El ID no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

