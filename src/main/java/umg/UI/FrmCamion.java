    private void configurarTabla() {
        modeloTabla = new DefaultTableModel(new String[]{"ID", "Modelo", "Tipo", "Potencia", "No. Placa"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblCamiones.setModel(modeloTabla);
        tblCamiones.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                seleccionarFila();
            }
        });
    }

    private void cargarCamiones() {
        modeloTabla.setRowCount(0);
        List<Camion> lista = camionDAO.listar();
        for (Camion c : lista) {
            modeloTabla.addRow(new Object[]{
                c.getIdCamion(),
                c.getModelo(),
                c.getTipo(),
                c.getPotencia(),
                c.getNoPlaca()
            });
        }
    }

    private void seleccionarFila() {
        int fila = tblCamiones.getSelectedRow();
        if (fila >= 0) {
            txtId.setText(tblCamiones.getValueAt(fila, 0).toString());
            txtModelo.setText(tblCamiones.getValueAt(fila, 1).toString());
            txtTipo.setText(tblCamiones.getValueAt(fila, 2).toString());
            txtPotencia.setText(tblCamiones.getValueAt(fila, 3).toString());
            txtPlaca.setText(tblCamiones.getValueAt(fila, 4).toString());
            
            txtId.setEnabled(false);
        }
    }

    private void limpiarCampos() {
        txtId.setText("");
        txtModelo.setText("");
        txtTipo.setText("");
        txtPotencia.setText("");
        txtPlaca.setText("");
        tblCamiones.clearSelection();
        txtId.setEnabled(false);
    }

    private boolean validarCampos() {
        if (txtModelo.getText().trim().isEmpty() ||
            txtTipo.getText().trim().isEmpty() ||
            txtPotencia.getText().trim().isEmpty() ||
            txtPlaca.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Validación", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        try {
            BigDecimal potencia = new BigDecimal(txtPotencia.getText().trim());
            if (potencia.compareTo(BigDecimal.ZERO) <= 0) {
                JOptionPane.showMessageDialog(this, "La potencia debe ser mayor a cero.", "Validación", JOptionPane.WARNING_MESSAGE);
                return false;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La potencia debe ser un número decimal válido.", "Validación", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        return true;
    }  
   
