    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (!validarCampos()) return;

        Camionero c = new Camionero();
        c.setNombre(txtNombre.getText().trim());
        c.setApellidos(txtApellidos.getText().trim());
        c.setDireccion(txtDireccion.getText().trim());
        c.setSalario(new BigDecimal(txtSalario.getText().trim()));
        c.setPoblacion(txtPoblacion.getText().trim());
        c.setTelefono(txtTelefono.getText().trim());

        if (camioneroDAO.insertar(c)) {
            JOptionPane.showMessageDialog(this, "Camionero guardado exitosamente.");
            cargarCamioneros();
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar camionero.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
       if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un camionero de la tabla para actualizar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!validarCampos()) return;

        try {
            Camionero c = new Camionero();
            c.setIdCamionero(Integer.parseInt(txtId.getText().trim()));
            c.setNombre(txtNombre.getText().trim());
            c.setApellidos(txtApellidos.getText().trim());
            c.setDireccion(txtDireccion.getText().trim());
            c.setSalario(new BigDecimal(txtSalario.getText().trim()));
            c.setPoblacion(txtPoblacion.getText().trim());
            c.setTelefono(txtTelefono.getText().trim());

            if (camioneroDAO.actualizar(c)) {
                JOptionPane.showMessageDialog(this, "Camionero actualizado exitosamente.");
                cargarCamioneros();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "Error al actualizar camionero.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un camionero de la tabla para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int op = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el camionero seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (op == JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(txtId.getText().trim());
                if (camioneroDAO.eliminar(id)) {
                    JOptionPane.showMessageDialog(this, "Camionero eliminado exitosamente.");
                    cargarCamioneros();
                    limpiarCampos();
                } else {
                    JOptionPane.showMessageDialog(this, "Error al eliminar camionero.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El ID no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

