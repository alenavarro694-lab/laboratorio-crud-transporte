    private void configurarTabla() {
        modeloTabla = new DefaultTableModel(new String[]{"ID", "Nombre", "Apellidos", "Dirección", "Salario", "Población", "Teléfono"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblCamioneros.setModel(modeloTabla);
        tblCamioneros.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                seleccionarFila();
            }
        });
    }

    private void cargarCamioneros() {
        modeloTabla.setRowCount(0);
        List<Camionero> lista = camioneroDAO.listar();
        for (Camionero c : lista) {
            modeloTabla.addRow(new Object[]{
                c.getIdCamionero(),
                c.getNombre(),
                c.getApellidos(),
                c.getDireccion(),
                c.getSalario(),
                c.getPoblacion(),
                c.getTelefono()
            });
        }
    }

    private void seleccionarFila() {
        int fila = tblCamioneros.getSelectedRow();
        if (fila >= 0) {
            txtId.setText(tblCamioneros.getValueAt(fila, 0).toString());
            txtNombre.setText(tblCamioneros.getValueAt(fila, 1).toString());
            txtApellidos.setText(tblCamioneros.getValueAt(fila, 2).toString());
            txtDireccion.setText(tblCamioneros.getValueAt(fila, 3).toString());
            txtSalario.setText(tblCamioneros.getValueAt(fila, 4).toString());
            txtPoblacion.setText(tblCamioneros.getValueAt(fila, 5).toString());
            txtTelefono.setText(tblCamioneros.getValueAt(fila, 6).toString());
            
            txtId.setEnabled(false);
        }
    }

    private void limpiarCampos() {
        txtId.setText("");
        txtNombre.setText("");
        txtApellidos.setText("");
        txtDireccion.setText("");
        txtSalario.setText("");
        txtPoblacion.setText("");
        txtTelefono.setText("");
        tblCamioneros.clearSelection();
        txtId.setEnabled(false);
    }

    private boolean validarCampos() {
        if (txtNombre.getText().trim().isEmpty() ||
            txtApellidos.getText().trim().isEmpty() ||
            txtDireccion.getText().trim().isEmpty() ||
            txtSalario.getText().trim().isEmpty() ||
            txtPoblacion.getText().trim().isEmpty() ||
            txtTelefono.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Validación", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        try {
            BigDecimal salario = new BigDecimal(txtSalario.getText().trim());
            if (salario.compareTo(BigDecimal.ZERO) < 0) {
                JOptionPane.showMessageDialog(this, "El salario debe ser mayor o igual a 0.", "Validación", JOptionPane.WARNING_MESSAGE);
                return false;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El salario debe ser un número válido.", "Validación", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        return true;
    }
    
